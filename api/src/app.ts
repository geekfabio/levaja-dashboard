export async function buildApp() {
  const env = loadEnv();
  const app = Fastify({ logger: true });

  await app.register(cors, { origin: env.CORS_ORIGINS.length > 0 ? env.CORS_ORIGINS : true, credentials: true });
  await app.register(cookie, { secret: env.ADMIN_SESSION_SECRET });
  await app.register(multipart, { limits: { fileSize: 15 * 1024 * 1024 } });

  registerErrorHandler(app);

  await app.register(healthRoutes);
  await app.register(authRoutes);
  await app.register(accountsRoutes);
  await app.register(adminAuthRoutes);
  await app.register(requestRoutes);
  await app.register(supportMobileRoutes);
  await app.register(providerRoutes);
  await app.register(locationRoutes);
  await app.register(vehicleRoutes);
  await app.register(applicationRoutes);
  await app.register(uploadRoutes);
  await app.register(crmCompaniesRoutes);
  await app.register(crmContactsRoutes);
  await app.register(crmOpportunitiesRoutes);
  await app.register(crmTicketsRoutes);
  await app.register(crmActivitiesRoutes);
  await app.register(crmConversationsRoutes);
  await app.register(crmDocumentsRoutes);
  await app.register(crmCampaignsRoutes);
  await app.register(crmAutomationsRoutes);
  await app.register(crmOffersRoutes);
  await app.register(paymentRoutes);
  await app.register(chatRoutes);
  await app.register(deviceRoutes);
  await app.register(adminRequestRoutes);
  await app.register(adminProviderRoutes);
  await app.register(adminApplicationRoutes);
  await app.register(adminClientRoutes);
  await app.register(adminDocumentRoutes);
  await app.register(adminRefundRoutes);
  await app.register(adminDisputeRoutes);
  await app.register(adminClaimRoutes);
  await app.register(adminZoneRoutes);
  await app.register(adminPricingRoutes);
  await app.register(adminPromotionsRoutes);
  await app.register(adminOperationsRoutes);
  await app.register(adminSecurityRoutes);
  await app.register(adminSettingsRoutes);
  await app.register(adminAuditRoutes);
  await app.register(adminMetricsRoutes);
  await app.register(adminFinanceRoutes);
  await app.register(adminBillingRoutes);
  await app.register(adminPrivacyRoutes);
  await app.register(adminFleetRoutes);
  await app.register(adminSupportRoutes);
  await app.register(adminIntegrationsRoutes);
  await app.register(adminCommunicationsRoutes);
  await app.register(adminBusinessRoutes);
  await app.register(adminQualityRoutes);

  return app;
}
